/// <reference types="node" />
/**
 * bundle-content.ts — run with:  npm run bundle-content
 *
 * Writes src/content/bundled.generated.ts: the small OFFLINE set of content
 * that is packed inside the app (the newest few days, plus the index).
 * The app uses it when there is no internet and nothing is cached yet.
 *
 * Run it before building the app or website. Live content does NOT need
 * this — the app downloads new drops from the website by itself.
 */
import fs from 'node:fs';
import path from 'node:path';

import { ContentIndexSchema } from '../src/lib/schema';
import { INDEX_FILE, ROOT_DIR, rel } from './lib/content-files';

/** How many of the newest days to pack into the app. */
const BUNDLED_DAYS = 2;
const OUT_FILE = path.join(ROOT_DIR, 'src', 'content', 'bundled.generated.ts');

function main(): void {
  if (!fs.existsSync(INDEX_FILE)) {
    console.error('✖ content/index.json is missing. Run "npm run build-index" first.');
    process.exit(1);
  }
  const index = ContentIndexSchema.parse(JSON.parse(fs.readFileSync(INDEX_FILE, 'utf8')));

  const dates = [...new Set(index.drops.map((d) => d.date))].sort().slice(-BUNDLED_DAYS);
  const entries = index.drops.filter((d) => dates.includes(d.date));

  const lines = [
    '// AUTO-GENERATED by scripts/bundle-content.ts — do not edit by hand.',
    `// Offline content packed inside the app: ${dates.join(', ') || 'none'}.`,
    '',
    "import index from '../../content/index.json';",
    ...entries.map((e, i) => `import drop${i} from '../../content/${e.path}';`),
    '',
    '/** The content index at build time (checked with Zod when the app starts). */',
    'export const bundledIndex: unknown = index;',
    '',
    '/** Drop files packed in the app, keyed by their path inside content/. */',
    'export const bundledDrops: Record<string, unknown> = {',
    ...entries.map((e, i) => `  '${e.path}': drop${i},`),
    '};',
    '',
  ];

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, lines.join('\n'), 'utf8');
  console.log(`✔ Wrote ${rel(OUT_FILE)}: ${entries.length} drops from ${dates.join(', ')}.`);
}

main();
